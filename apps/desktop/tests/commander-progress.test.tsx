import { act, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { expect, it } from "vitest";
import { CommanderView } from "../src/components/CommanderView";
import type { RunView } from "../src/lib/commander";
import { calls, Channel, handle } from "./fixtures/tauri";
it("continues while hidden, rereads notifications during reads and ignores stale progress after completion", async () => {
  const task = { id: "one", title: "任务", agent_id: "opencode", prompt: "fixture", depends_on: [] };
  const draft: RunView = { run: { id: "run", cwd: "/fixture", status: "draft", plan: { objective: "测试", tasks: [task] } }, summary: { tasks: [{ ...task, status: "pending", session_id: null, agent_session_id: null, result: null, truncated: false }] }, batches: [["one"]], active: false };
  const running = { ...draft, run: { ...draft.run, status: "running" as const }, active: true };
  const done = { ...draft, run: { ...draft.run, status: "succeeded" as const } };
  handle("get_commander_config", () => null);
  handle("list_agent_definitions", () => []);
  handle("list_commander_run_views", () => [draft]);
  let channel!: Channel<string>;
  let finish!: (view: RunView) => void;
  handle("execute_commander_run", (args) => {
    channel = args.onProgress as Channel<string>;
    return new Promise<RunView>((resolve) => { finish = resolve; });
  });
  const props = { active: true, onSettings: () => {} };
  const host = render(<CommanderView {...props} />);
  fireEvent.click(await screen.findByRole("button", { name: "计划历史（1）" }));
  fireEvent.click(screen.getByRole("button", { name: /测试.*等待确认/ }));
  fireEvent.click(screen.getByRole("button", { name: "审阅并执行" }));
  fireEvent.click(screen.getByRole("button", { name: "确认执行" }));
  await waitFor(() => expect(channel).toBeDefined());
  const reads: ((view: RunView) => void)[] = [];
  handle("get_commander_run_view", () => new Promise<RunView>((resolve) => { reads.push(resolve); }));
  act(() => { channel.onmessage("one"); channel.onmessage("one"); });
  await waitFor(() => expect(reads).toHaveLength(1));
  host.rerender(<CommanderView {...props} active={false} />);
  await act(async () => { reads[0](running); });
  await waitFor(() => expect(reads).toHaveLength(2));
  handle("get_commander_run_view", () => done);
  await act(async () => { finish(done); });
  await act(async () => { reads[1](running); });
  expect(screen.getByText(/\/fixture · 已完成/)).toBeVisible();
  expect(calls.filter((call) => call.command === "execute_commander_run")).toHaveLength(1);
  expect(calls.filter((call) => /cancel|run_prompt/.test(call.command))).toHaveLength(0);
});
