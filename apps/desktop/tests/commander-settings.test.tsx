import { act, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { expect, it } from "vitest";
import { CommanderSettings } from "../src/components/CommanderSettings";
import { calls, handle } from "./fixtures/tauri";
const config = { endpoint: "http://localhost:18518/v1", model: "fixture", api_key_env: "FIXTURE_KEY", timeout_secs: 10 };
const plan = { plan: { objective: "fixture", tasks: [{ id: "one", title: "示例任务", agent_id: "opencode", prompt: "only plan", depends_on: [] }] }, batches: [["one"]] };
it("separates saved connection and key from verification, locks duplicate calls and invalidates on change", async () => {
  handle("get_commander_config", () => config);
  handle("commander_credential_source", () => "sqlite");
  let resolve!: (value: typeof plan) => void;
  handle("verify_commander_plan", () => new Promise((done) => { resolve = done; }));
  const view = render(<CommanderSettings />);
  await waitFor(() => expect(screen.getByRole("button", { name: "验证模型并生成示例计划" })).toBeEnabled());
  expect(screen.getByRole("status", { name: "模型验证状态" })).toHaveTextContent("未验证");
  const verify = screen.getByRole("button", { name: "验证模型并生成示例计划" });
  fireEvent.click(verify); fireEvent.click(verify);
  expect(calls.filter((c) => c.command === "verify_commander_plan")).toHaveLength(1);
  await act(async () => resolve(plan));
  expect(screen.getByRole("status", { name: "模型验证状态" })).toHaveTextContent("验证通过");
  fireEvent.change(screen.getByLabelText("指挥官模型名"), { target: { value: "another" } });
  expect(screen.getByRole("status", { name: "模型验证状态" })).toHaveTextContent("未验证");
  expect(screen.getByRole("button", { name: "验证模型并生成示例计划" })).toBeDisabled();
  view.unmount(); render(<CommanderSettings />);
  await waitFor(() => expect(screen.getByRole("button", { name: "验证模型并生成示例计划" })).toBeEnabled());
  expect(screen.getByRole("status", { name: "模型验证状态" })).toHaveTextContent("未验证");
  expect(calls.filter((c) => /run_prompt|execute_commander|save_commander_key/.test(c.command))).toHaveLength(0);
});
it("retains verification failure until explicit retry and clears key without reading it back", async () => {
  handle("get_commander_config", () => config); handle("commander_credential_source", () => "missing");
  handle("save_commander_key", () => undefined);
  render(<CommanderSettings />);
  await waitFor(() => expect(screen.getByLabelText("指挥官 API key")).toBeEnabled());
  fireEvent.change(screen.getByLabelText("指挥官 API key"), { target: { value: "synthetic-only" } });
  fireEvent.click(screen.getByRole("button", { name: "保存密钥到本机" }));
  await waitFor(() => expect(screen.getByLabelText("指挥官 API key")).toHaveValue(""));
  expect(screen.getByRole("status", { name: "模型验证状态" })).toHaveTextContent("未验证");
  handle("verify_commander_plan", () => { throw new Error("合成服务不可用"); });
  fireEvent.click(screen.getByRole("button", { name: "验证模型并生成示例计划" }));
  await screen.findByText(/合成服务不可用/);
  expect(screen.getByRole("status", { name: "模型验证状态" })).toHaveTextContent("验证失败");
  handle("verify_commander_plan", () => plan);
  fireEvent.click(screen.getByRole("button", { name: "验证模型并生成示例计划" }));
  await waitFor(() => expect(screen.getByRole("status", { name: "模型验证状态" })).toHaveTextContent("验证通过"));
});
it("cancels verification explicitly and never turns a cancelled request into a passed result", async () => {
  handle("get_commander_config", () => config); handle("commander_credential_source", () => "sqlite");
  let reject!: (reason: Error) => void;
  handle("verify_commander_plan", () => new Promise((_, fail) => { reject = fail; }));
  handle("cancel_commander_plan", () => { reject(new Error("已取消")); });
  render(<CommanderSettings />);
  await waitFor(() => expect(screen.getByRole("button", { name: "验证模型并生成示例计划" })).toBeEnabled());
  fireEvent.click(screen.getByRole("button", { name: "验证模型并生成示例计划" }));
  fireEvent.click(screen.getByRole("button", { name: "取消验证" }));
  await waitFor(() => expect(screen.getByRole("status", { name: "模型验证状态" })).toHaveTextContent("已取消验证"));
  expect(calls.filter((c) => c.command === "cancel_commander_plan")).toHaveLength(1);
});
